use pkhex_core::binary::InvalidData;
pub fn is_valid(data: &[u8]) -> bool { data.len() >= 0x8a44 && data.starts_with(b"PKR-059\0a00") }

fn crypt(words: &mut [u32]) {
    let mut seed = words[0];
    for word in &mut words[1..] {
        let high = 1566083941_u32.wrapping_mul(seed);
        seed = 1566083941_u32.wrapping_mul(high);
        *word ^= (high & 0xffff0000) | (seed >> 16);
    }
}

pub fn decrypt(input: &[u8]) -> Result<Vec<u8>, InvalidData> {
    let mut words: Vec<_> = input.chunks_exact(4).map(|b| u32::from_le_bytes([b[0], b[1], b[2], b[3]])).collect();
    if words[4] >> 16 == 0 { return Err(InvalidData("Ranger save information is already decrypted.")); }
    crypt(&mut words[3..128]);
    crypt(&mut words[0x20c / 4..0x400 / 4]);
    for index in 0..10 {
        let header = 3 + 0xc + index * 0xc;
        let count = (words[header] >> 16) & 0xff;
        if count == 0 { continue; }
        let offset = words[header + 1] as usize;
        let size = words[header + 2] as usize;
        let chunk_size = words[header + 3] as usize / count as usize;
        if offset == 0 || chunk_size > 0x40000 { continue; }
        for chunk in 0..count.min(3) as usize {
            let start = (offset + chunk_size * chunk) / 4;
            let length = (size + 0x18) / 4;
            let end = start.checked_add(length).ok_or(InvalidData("Ranger chunk overflow."))?;
            if length == 0 || length > chunk_size / 4 { return Err(InvalidData("Invalid Ranger chunk size.")); }
            crypt(words.get_mut(start..end).ok_or(InvalidData("Truncated Ranger chunk."))?);
        }
    }
    let mut output = input.to_vec();
    for (word, bytes) in words.iter().zip(output.chunks_exact_mut(4)) { bytes.copy_from_slice(&word.to_le_bytes()); }
    Ok(output)
}

